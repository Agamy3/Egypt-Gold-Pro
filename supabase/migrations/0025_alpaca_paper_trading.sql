-- Alpaca Paper Trading (ADMIN-ONLY) tables
-- NOTE: These tables are isolated from other bot tables to avoid mixing state/logs.

-- 1) Settings (single row by key='default')
create table if not exists public.alpaca_paper_settings (
  key text primary key,
  enabled boolean not null default false,
  interval_seconds int not null default 60,
  max_risk_per_trade_pct numeric not null default 0.02,
  max_daily_drawdown_pct numeric not null default 0.05,
  universe jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2) State (single row by key='default')
create table if not exists public.alpaca_paper_state (
  key text primary key,
  last_run_at timestamptz,
  last_run_minute_key text,
  halted boolean not null default false,
  halted_reason text,
  reserved_cash numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 3) Trades log
create table if not exists public.alpaca_paper_trades (
  id bigint generated by default as identity primary key,
  run_id uuid not null,
  created_at timestamptz not null default now(),
  symbol text not null,
  side text not null check (side in ('BUY','SELL')),
  qty numeric not null,
  notional numeric,
  entry_price numeric,
  stop_loss numeric,
  take_profit numeric,
  order_id text,
  status text not null default 'submitted',
  filled_avg_price numeric,
  filled_at timestamptz,
  pnl numeric,
  meta jsonb
);

create index if not exists idx_alpaca_paper_trades_created_at_desc on public.alpaca_paper_trades(created_at desc);
create index if not exists idx_alpaca_paper_trades_symbol on public.alpaca_paper_trades(symbol);

-- 4) Positions snapshot (for UI/history)
create table if not exists public.alpaca_paper_positions_snapshot (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  positions jsonb not null
);

-- 5) Long-term holdings (virtual bucket)
create table if not exists public.alpaca_long_term_holdings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  symbol text not null,
  qty numeric not null,
  avg_price numeric,
  source_trade_id bigint references public.alpaca_paper_trades(id)
);

create index if not exists idx_alpaca_long_term_holdings_created_at_desc on public.alpaca_long_term_holdings(created_at desc);
create index if not exists idx_alpaca_long_term_holdings_symbol on public.alpaca_long_term_holdings(symbol);

-- 6) Reserve ledger (virtual cash bucket)
create table if not exists public.alpaca_reserve_ledger (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  amount numeric not null,
  reason text not null,
  source_trade_id bigint references public.alpaca_paper_trades(id)
);

create index if not exists idx_alpaca_reserve_ledger_created_at_desc on public.alpaca_reserve_ledger(created_at desc);

-- Defaults
insert into public.alpaca_paper_settings(key, enabled, interval_seconds, max_risk_per_trade_pct, max_daily_drawdown_pct, universe)
values (
  'default',
  false,
  60,
  0.02,
  0.05,
  '["SPY","QQQ","DIA","IWM","GLD","SLV","TLT","AAPL","MSFT","AMZN","GOOGL","NVDA","META","JNJ","PG","KO"]'::jsonb
)
on conflict (key) do nothing;

insert into public.alpaca_paper_state(key)
values ('default')
on conflict (key) do nothing;

