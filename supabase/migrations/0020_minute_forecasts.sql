-- Dedicated per-minute forecast stream (decoupled from trades).
-- This table is meant to be appended/upserted once per minute_key, independent of trade validation.

create table if not exists public.minute_forecasts (
  id bigint generated by default as identity primary key,
  minute_key text not null,
  country text not null,
  scope text not null default 'local',
  karat int not null,
  p0 numeric,
  predicted_price numeric,
  direction text not null check (direction in ('UP','DOWN','TIE','STALE','NA')),
  confidence numeric,
  provider text,
  source text,
  meta jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- One row per minute+dimension
create unique index if not exists uq_minute_forecasts_minute_country_karat
  on public.minute_forecasts(minute_key, country, karat);

create index if not exists idx_minute_forecasts_created_at_desc
  on public.minute_forecasts(created_at desc);

-- Optional: enable RLS (service_role bypasses anyway); allow only admins via admin_users.
alter table public.minute_forecasts enable row level security;

drop policy if exists "admins can read minute_forecasts" on public.minute_forecasts;
create policy "admins can read minute_forecasts"
  on public.minute_forecasts
  for select
  using (exists(select 1 from public.admin_users au where au.user_id = auth.uid()));

drop policy if exists "admins can write minute_forecasts" on public.minute_forecasts;
create policy "admins can write minute_forecasts"
  on public.minute_forecasts
  for all
  using (exists(select 1 from public.admin_users au where au.user_id = auth.uid()))
  with check (exists(select 1 from public.admin_users au where au.user_id = auth.uid()));

